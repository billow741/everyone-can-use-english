export interface PhonicsAnchorItem {
  id: string; // 唯一键，如 'm', 'c_k', 'sh', 'th_voiced', 'a', 'a_long', 'ar'
  letter: string; // 儿童视角大字母，如 'c / k', 'sh', 'a', 'ā', 'ar', 'qu', 'x'
  zone: PhonicsIslandZone;
  zoneName: string; // '辅音岛' | '短元音湾' | '长元音峰' | 'r 音谷'
  order: number; // 1 ~ 39
  anchorWord: string; // 'cat', 'ship', 'apple', etc.
  anchorZh: string; // '小猫', '轮船', '苹果', etc.
  mnemonic: string; // 少儿拟声口诀，如 '小火车开来嚓嚓嚓'
  imageFile: string; // 'anchor-cat.webp'
  imageUrl: string; // '/assets/phonics/anchors/anchor-cat.webp'
  colorBg: string; // 糖果渐变底色
  ipaSymbol: string; // 国际音标符号，家长模式呈现，如 '/k/', '/ʃ/'
  ipaSlug: string; // 对应 /phonemes/:slug 页面路径
  academicName: string; // 学术分类，如 '舌根清塞音', '清擦嘘音'
  voiced: boolean; // 声带是否震动
}

