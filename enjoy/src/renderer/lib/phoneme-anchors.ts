// 向下兼容接口
export interface PhonemeAnchor {
  id: string;
  symbol: string;
  anchorWord: string;
  anchorZh: string;
  mnemonic: string;
  emoji: string;
  imageUrl?: string;
  colorBg: string;
}

export function getPhonemeAnchor(idOrSlug: string): PhonemeAnchor {
  const clean = idOrSlug.replace(/[\/\[\]]/g, "").trim();
  const matched =
    ANCHOR_BY_ID.get(clean) ||
    ANCHOR_BY_IPA.get(clean) ||
    ANCHOR_BY_SLUG.get(clean.toLowerCase()) ||
    ANCHOR_BY_LETTER.get(clean.toLowerCase());

  if (matched) {
    return {
      id: matched.id,
      symbol: matched.ipaSymbol,
      anchorWord: matched.anchorWord,
      anchorZh: matched.anchorZh,
      mnemonic: matched.mnemonic,
      emoji: "🌟",
      imageUrl: matched.imageUrl,
      colorBg: matched.colorBg,
    };
  }

  return {
    id: clean,
    symbol: `/${clean}/`,
    anchorWord: clean,
    anchorZh: "发音通关",
    mnemonic: "跟着敢敢大声读",
    emoji: "🌟",
    colorBg: "from-amber-100 to-orange-100",
  };
}

